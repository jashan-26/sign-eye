-- SQLite now, PostgreSQL-ready (swap AUTOINCREMENT for IDENTITY).
CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS signs (id INTEGER PRIMARY KEY AUTOINCREMENT, label TEXT UNIQUE NOT NULL, category TEXT NOT NULL, difficulty TEXT NOT NULL DEFAULT 'beginner');
CREATE TABLE IF NOT EXISTS predictions (
  id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER REFERENCES users(id), session_id TEXT,
  gesture TEXT NOT NULL, confidence REAL NOT NULL, hand_count INTEGER NOT NULL, inference_ms REAL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS translations (
  id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER REFERENCES users(id), session_id TEXT,
  signs TEXT NOT NULL, sentence TEXT NOT NULL, avg_confidence REAL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS practice_sessions (
  id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER REFERENCES users(id), sign_id INTEGER REFERENCES signs(id),
  level TEXT, similarity REAL, passed INTEGER NOT NULL DEFAULT 0, xp_awarded INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS badges (
  id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER REFERENCES users(id), code TEXT NOT NULL,
  earned_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id, code));
CREATE TABLE IF NOT EXISTS learning_progress (
  user_id INTEGER REFERENCES users(id), sign_id INTEGER REFERENCES signs(id),
  best_similarity REAL NOT NULL DEFAULT 0, attempts INTEGER NOT NULL DEFAULT 0, learned INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, sign_id));
CREATE TABLE IF NOT EXISTS xp_events (
  id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER REFERENCES users(id), amount INTEGER NOT NULL,
  reason TEXT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
